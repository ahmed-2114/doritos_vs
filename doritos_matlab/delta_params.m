function params = delta_params()

Rb = 0.0610;
Rp = 0.0440;
L1 = 0.0800;
L2 = 0.1557;

% Default simulation pose: theta = [0 0 0] deg at the workspace centre.
r_home = Rb - Rp + L1;
z_home = -sqrt(max(L2^2 - r_home^2, 0));

params = struct( ...
    'Rb', Rb, ...
    'Rp', Rp, ...
    'L1', L1, ...
    'L2', L2, ...
    'phi', [0, 2*pi/3, 4*pi/3], ...
    'th_min', deg2rad(0), ...
    'th_max', deg2rad(100), ...
    'ws_lim', [ -0.20, 0.20; ...
                -0.20, 0.20; ...
                -0.30, 0.00 ], ...
    'home_pos', [0; 0; z_home], ...
    'f_base', sqrt(3)*Rb, ...
    'e_platform', sqrt(3)*Rp ...
    );
end